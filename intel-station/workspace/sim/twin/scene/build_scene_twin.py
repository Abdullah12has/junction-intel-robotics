"""Build the twin scene MuJoCo MJCF (scene_twin_v1.xml) from the E1 measurement files.

Inputs, read from this folder:
  scene_measurements.json  mat height and extent, plate positions and geometry, brick size, mass, friction
  colour_tables.json       rgb_mjcf values for the bricks, plates and mat (visual only)
Output:
  scene_twin_v1.xml        base frame, metres, written next to this script

Run:
  /home/intel/intel-junction-2026/envs/sim-env/bin/python -I build_scene_twin.py

Values that are NOT in the JSON files (also flagged in the XML comments):
  LAYOUT   nominal brick positions, placed by eye from ep_0001/pre_top.jpg (ASSUMED)
  DECAL    tape decal faces and sizes, eyeballed from close_color.jpg (approximate, visual only)
  light    one neutral directional light (ASSUMED; the lighting values are image-derived only)
"""

import json
import math
import os

import mujoco

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "scene_twin_v1.xml")
MM = 0.001

LAYOUT = [
    {"id": "blue", "on": "green"},
    {"id": "orange", "on": "blue"},
    {"id": "yellow", "on": "mat", "xy_mm": [50.0, 50.0]},
    {"id": "white", "on": "mat", "xy_mm": [-50.0, 100.0]},
]
DECAL = {
    "blue": {"face": "-x", "w_mm": 12.0, "h_mm": 8.0},
    "yellow": {"face": "+y", "w_mm": 12.0, "h_mm": 8.0},
}
COLOUR_KEY = {"blue": "brick_blue", "orange": "brick_orange",
              "yellow": "brick_yellow", "white": "brick_white"}


def load(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return json.load(fh)


def rgba(rgb255):
    return " ".join(f"{c / 255.0:.4f}" for c in rgb255) + " 1"


def build_xml(M, C):
    col = {e["id"]: e for e in C["entries"]}
    mat_z = M["mat"]["surface_z_base_mm"] * MM
    extent = M["mat"]["extent_mm"] * MM
    plates = M["plates"]["PLATES_XY_base_mm"]
    r_out = M["plates"]["outer_radius_mm"]["used"] * MM
    r_in = M["plates"]["inner_radius_mm"]["used"] * MM
    wall = M["plates"]["wall_width_mm"]["used"] * MM
    rim_top = M["plates"]["rim_top_above_mat_mm"]["used"] * MM
    floor_top = M["plates"]["floor_top_above_mat_mm"]["used"] * MM
    n_rim = int(M["plates"]["segments"])
    foot = M["bricks"]["footprint_used_mm"] * MM
    h = M["bricks"]["height_used_mm"] * MM
    fric = M["bricks"]["sliding_friction"]
    rho = M["bricks"]["density_g_cm3"] * 1000.0  # kg/m3
    mass = foot * foot * h * rho  # kg, solid-body upper bound
    if abs(mass * 1000.0 - M["bricks"]["mass_upper_bound_g"]) > 0.02:
        raise SystemExit("mass check failed: %.4f g" % (mass * 1000.0))
    if abs((r_out - wall) - r_in) > 0.05 * MM:
        raise SystemExit("inner radius disagrees with outer radius minus wall")
    if rim_top <= floor_top:
        raise SystemExit("rim top must be above the floor top")

    mat_rgba = rgba(col["mat_black"]["rgb_mjcf"])
    tape_rgba = rgba(col["tape_dark"]["rgb_mjcf"])
    r_mid = 0.5 * (r_in + r_out)
    half_radial = 0.5 * (r_out - r_in)
    half_tang = math.pi * 2.0 * r_mid / n_rim / 2.0 * 1.05  # 5 percent overlap between segments
    half_vert = 0.5 * (rim_top - floor_top)
    z_rim = 0.5 * (rim_top + floor_top)

    L = []
    add = L.append
    add('<mujoco model="scene_twin_v1">')
    add('  <!-- Generated by build_scene_twin.py from scene_measurements.json and colour_tables.json. Base frame, metres.')
    add('       FLAGS: mat extent ASSUMED 1.2 m; plate positions = PLATES_XY (sort_any.py:33), NOT depth-verified;')
    add('       plate radius, wall, rim and floor LOW confidence; brick mass ASSUMED upper bound (not weighed);')
    add('       friction ASSUMED 0.35; brick layout NOMINAL; tape decals approximate and visual only (no contact);')
    add('       light is neutral and not photometric. See README.md. -->')
    add('  <compiler angle="degree"/>')
    add('  <option timestep="0.002" gravity="0 0 -9.81"/>')
    add('  <worldbody>')
    add('    <light name="scene_light" pos="0 0 1.5" dir="0 0 -1" directional="true"'
        ' diffuse="0.8 0.8 0.8" ambient="0.2 0.2 0.2"/>')
    add(f'    <!-- mat: top surface at MAT_Z = {M["mat"]["surface_z_base_mm"]} mm (kin.py:24); extent ASSUMED -->')
    add(f'    <geom name="mat" type="box" size="{0.5 * extent:.4f} {0.5 * extent:.4f} 0.001"'
        f' pos="0 0 {mat_z - 0.001:.5f}" rgba="{mat_rgba}" friction="{fric} 0.005 0.0001"/>')

    for name, (x_mm, y_mm) in plates.items():
        prgba = rgba(col["plate_" + name]["rgb_mjcf"])
        add(f'    <!-- plate {name}: PLATES_XY base ({x_mm}, {y_mm}) mm, NOT depth-verified; '
            f'{n_rim} rim boxes + floor disc -->')
        add(f'    <body name="plate_{name}" pos="{x_mm * MM:.5f} {y_mm * MM:.5f} {mat_z:.5f}">')
        add(f'      <geom name="plate_{name}_floor" type="cylinder" size="{r_in:.5f} {0.5 * floor_top:.5f}"'
            f' pos="0 0 {0.5 * floor_top:.5f}" rgba="{prgba}"/>')
        for i in range(n_rim):
            th = 360.0 * i / n_rim
            px = r_mid * math.cos(math.radians(th))
            py = r_mid * math.sin(math.radians(th))
            add(f'      <geom name="plate_{name}_rim_{i:02d}" type="box"'
                f' size="{half_radial:.5f} {half_tang:.5f} {half_vert:.5f}"'
                f' pos="{px:.5f} {py:.5f} {z_rim:.5f}" euler="0 0 {th:.2f}" rgba="{prgba}"/>')
        add('    </body>')

    for item in LAYOUT:
        bid = item["id"]
        on_txt = item["on"]
        if on_txt == "mat":
            x_mm, y_mm = item["xy_mm"]
            z0 = mat_z
        else:
            x_mm, y_mm = plates[on_txt]
            z0 = mat_z + floor_top
        brgba = rgba(col[COLOUR_KEY[bid]]["rgb_mjcf"])
        zc = z0 + 0.5 * h
        add(f'    <!-- brick {bid} on {on_txt}: footprint {M["bricks"]["footprint_used_mm"]} mm, '
            f'height {M["bricks"]["height_used_mm"]} mm, mass upper bound {mass * 1000:.2f} g (not weighed) -->')
        add(f'    <body name="brick_{bid}" pos="{x_mm * MM:.5f} {y_mm * MM:.5f} {zc:.5f}">')
        add(f'      <freejoint name="brick_{bid}_free"/>')
        add(f'      <geom name="brick_{bid}_geom" type="box"'
            f' size="{0.5 * foot:.5f} {0.5 * foot:.5f} {0.5 * h:.5f}" mass="{mass:.5f}"'
            f' rgba="{brgba}" friction="{fric} 0.005 0.0001"/>')
        if bid in DECAL:
            d = DECAL[bid]
            tw = 0.5 * d["w_mm"] * MM
            th_h = 0.5 * d["h_mm"] * MM
            thin = 0.0002
            if d["face"] == "-x":
                dpos = f"{-0.5 * foot - thin:.5f} 0 0"
                dsize = f"{thin:.5f} {tw:.5f} {th_h:.5f}"
            else:
                dpos = f"0 {0.5 * foot + thin:.5f} 0"
                dsize = f"{tw:.5f} {thin:.5f} {th_h:.5f}"
            add(f'      <geom name="brick_{bid}_tape" type="box" size="{dsize}" pos="{dpos}"'
                f' density="0" contype="0" conaffinity="0" rgba="{tape_rgba}"/>')
        add('    </body>')

    add('  </worldbody>')
    add('</mujoco>')
    return "\n".join(L) + "\n"


def main():
    M = load("scene_measurements.json")
    C = load("colour_tables.json")
    xml = build_xml(M, C)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(xml)

    model = mujoco.MjModel.from_xml_path(OUT)
    data = mujoco.MjData(model)
    print("mujoco", mujoco.__version__)
    print("wrote", OUT, "bytes", len(xml))
    print("bodies", model.nbody, "(includes world)  geoms", model.ngeom, "  joints", model.njnt)

    names = ["brick_" + item["id"] for item in LAYOUT]
    ids = [mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, n) for n in names]
    mujoco.mj_forward(model, data)
    start = [float(data.xpos[i][2]) for i in ids]
    for _ in range(1000):  # 2 s of simulated time
        mujoco.mj_step(model, data)
    end = [float(data.xpos[i][2]) for i in ids]
    worst = 0.0
    for n, a, b in zip(names, start, end):
        worst = max(worst, abs(b - a))
        print(f"  {n}: z start {a * 1000:.2f} mm, after 2 s {b * 1000:.2f} mm, drift {(b - a) * 1000:+.3f} mm")
    print(f"max brick drift over 2 s: {worst * 1000:.3f} mm", "OK" if worst < 0.001 else "WARNING")
    print("brick_blue body mass (g):", round(float(model.body_mass[ids[0]]) * 1000.0, 3), "(upper bound, not weighed)")

    print("lighting (image-derived, not photometric):")
    for key in ("top", "close", "servo_163312_p0_base", "servo_165016_a6_lift"):
        print(" ", key, json.dumps(M["lighting"][key]))


if __name__ == "__main__":
    main()
