#!/usr/bin/env python3
"""E1 step 2: build the SO-101 twin MJCF from OUR URDF (the geometry app/tools/kin.py uses; mesh visuals from
R/sim/twin/robot/meshes, which mesh_identity.py verified) and build the official plugin URDF as a comparison-only
MJCF (no visuals). Compares the two URDFs joint by joint and loads both models in MuJoCo.
Run after mesh_identity.py: nice -n 19 $SIM_PY -I make_twin.py"""
import hashlib
import json
import os
import sys

sys.path.insert(0, "/home/intel/intel-junction-2026/work/P3-TWIN-ROBOT/E1/tools")
import mujoco  # noqa: E402
import urdf_tools as ut  # noqa: E402

R = "/home/intel/intel-junction-2026"
E1 = f"{R}/work/P3-TWIN-ROBOT/E1"
OUR = (f"{R}/repos/edge-developer-kit-reference-scripts/samples/ai/edge-ai-demo-studio/workers/services/"
       "robotics-ai/platforms/so101/urdf/so101.urdf")
OFF = f"{R}/repos/physicalai/packages/physicalai-mujoco-plugin/urdf/so101/so101_new_calib.urdf"
TWIN_OUT = f"{R}/sim/twin/robot/so101_twin.xml"
OFF_OUT = f"{E1}/official_urdf_twin.xml"
TIP = "gripper_frame_link"


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def fmt(x):
    return "n/a" if x is None else f"{x:.6f}"


def main():
    ours = ut.parse_urdf(OUR)
    off = ut.parse_urdf(OFF)
    cmp = ut.compare_urdf(ours, off)
    twin_xml = ut.build_mjcf(ours, TIP, "so101_twin",
                             f"Generated by E1 (P3-TWIN-ROBOT) from {OUR}; meshes from meshes/ (verified, see README.md)",
                             with_visuals=True)
    off_xml = ut.build_mjcf(off, TIP, "so101_official_urdf",
                            f"Generated by E1 (P3-TWIN-ROBOT) from {OFF}; comparison only", with_visuals=False)
    os.makedirs(os.path.dirname(TWIN_OUT), exist_ok=True)
    with open(TWIN_OUT, "w", encoding="utf-8") as fh:
        fh.write(twin_xml)
    with open(OFF_OUT, "w", encoding="utf-8") as fh:
        fh.write(off_xml)
    checks = {}
    for label, path in (("twin", TWIN_OUT), ("official_urdf", OFF_OUT)):
        m = mujoco.MjModel.from_xml_path(path)
        checks[label] = {"path": path, "sha256": sha256(path), "nbody": int(m.nbody), "njnt": int(m.njnt),
                         "nsite": int(m.nsite), "ngeom": int(m.ngeom), "mujoco": mujoco.__version__}
    report = {
        "our_urdf": {"path": OUR, "sha256": sha256(OUR), "robot": ours["name"],
                     "joints": [j["name"] for j in ours["joints"]]},
        "official_urdf": {"path": OFF, "sha256": sha256(OFF), "robot": off["name"],
                          "joints": [j["name"] for j in off["joints"]]},
        "mjcf_built": checks,
        "compare_official_minus_ours": cmp,
    }
    with open(f"{E1}/urdf_compare.json", "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=1)
    print(json.dumps(checks, indent=1))
    print("joint differences, official vs ours (origin mm, origin deg, axis deg):")
    for name, v in cmp["joints"].items():
        print(f"{name:20s} {fmt(v['origin_xyz_diff_mm'])} {fmt(v['origin_rot_diff_deg'])} {fmt(v['axis_angle_diff_deg'])}")
    print("joints only in ours:", cmp["joints_only_in_a"], "only in official:", cmp["joints_only_in_b"])


if __name__ == "__main__":
    main()
